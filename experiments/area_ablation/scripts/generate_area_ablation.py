#!/usr/bin/env python3
"""Generate Ultra-DSP area-ablation RTL.

This script keeps the rebuttal RTL self-contained under area-ablation while
reusing the checked-in Ultra-DSP source files as the structural reference.
W4A4 is copied from the existing paper ablation sources; the other precisions
are generated by applying the same cumulative optimization toggles to their
current Hybrid PE RTL.
"""

from __future__ import annotations

import csv
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
REBUTTAL_ROOT = ROOT.parent
ULTRA_ROOT = REBUTTAL_ROOT / "Ultra-DSP-main"
CORE_RTL = ULTRA_ROOT / "DSP_Packaging_Verilog"
AREA_TEST = ULTRA_ROOT / "Area_Test_Ablation_Test"

OPT_DIR = ROOT / "rtl" / "optimization_stages"
LSB_DIR = ROOT / "rtl" / "lsb_depth_sweep"
MANIFEST = ROOT / "manifest.csv"


PRECISIONS = {
    "W3A4": {
        "w_bits": 3,
        "a_bits": 4,
        "w_count": 9,
        "source": CORE_RTL / "W3A4" / "W3A4_Hybrid.v",
    },
    "W3A5": {
        "w_bits": 3,
        "a_bits": 5,
        "w_count": 7,
        "source": CORE_RTL / "W3A5" / "W3A5_Hybrid.v",
    },
    "W4A4": {
        "w_bits": 4,
        "a_bits": 4,
        "w_count": 7,
        "source": CORE_RTL / "W4A4" / "W4A4_Hybrid.v",
    },
    "W4A5": {
        "w_bits": 4,
        "a_bits": 5,
        "w_count": 6,
        "source": CORE_RTL / "W4A5" / "W4A5_Hybrid.v",
    },
    "W5A4": {
        "w_bits": 5,
        "a_bits": 4,
        "w_count": 5,
        "source": CORE_RTL / "W5A4" / "W5A4_Hybrid.v",
    },
    "W5A5": {
        "w_bits": 5,
        "a_bits": 5,
        "w_count": 5,
        "source": CORE_RTL / "W5A5" / "W5A5_Hybrid.v",
    },
}


W4A4_STAGE_SOURCES = {
    "s0_original": (
        AREA_TEST
        / "Ablation Experiment"
        / "Ablation Experiment.srcs"
        / "sources_1"
        / "new"
        / "W4A4_PD_Original.v"
    ),
    "s1_weight_offline": (
        AREA_TEST
        / "Ablation Experiment"
        / "Ablation Experiment.srcs"
        / "sources_1"
        / "new"
        / "W4A4_PD_opt1.v"
    ),
    "s2_registered_c": (
        AREA_TEST
        / "Ablation Experiment"
        / "Ablation Experiment.srcs"
        / "sources_1"
        / "new"
        / "W4A4_PD_opt12.v"
    ),
    "s3_xor_sign": (
        AREA_TEST
        / "Compensation_Breakdown_Analysis"
        / "Compensation_Breakdown_Analysis.srcs"
        / "sources_1"
        / "new"
        / "W4A4_Hybrid.v"
    ),
}


STAGES = [
    (
        "s0_original",
        "runtime weight two's-complement conversion; combinational C-port; per-result two's-complement sign recovery",
    ),
    (
        "s1_weight_offline",
        "offline sign-magnitude weights; combinational C-port; per-result two's-complement sign recovery",
    ),
    (
        "s2_registered_c",
        "offline sign-magnitude weights; registered C-port; per-result two's-complement sign recovery",
    ),
    (
        "s3_xor_sign",
        "offline sign-magnitude weights; registered C-port; XOR-only magnitude/sign output",
    ),
]


XOR_RESULT_RE = re.compile(
    r"(?P<expr>\{1'b0,\s*res\d+_mag\}|res\d+_mag)\s*\^\s*"
    r"\{(?P<width>\d+)\{(?P<sign>signs_r3\[\d+\])\}\}"
)


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def top_module_name(text: str) -> str:
    match = re.search(r"\bmodule\s+([A-Za-z_][A-Za-z0-9_]*)\b", text)
    if not match:
        raise ValueError("Could not find a module declaration")
    return match.group(1)


def rename_top(text: str, new_top: str) -> str:
    old_top = top_module_name(text)
    return re.sub(rf"\bmodule\s+{re.escape(old_top)}\b", f"module {new_top}", text, count=1)


def verilog_literal(width: int, bits: str) -> str:
    return f"{width}'b{bits}"


def make_runtime_weight_conversion(text: str, precision: str) -> str:
    cfg = PRECISIONS[precision]
    w_bits = cfg["w_bits"]
    mag_bits = w_bits - 1
    names = [f"w{i}" for i in range(1, cfg["w_count"] + 1)]

    min_negative = "1" + ("0" * (w_bits - 1))
    saturated_mag = "1" * mag_bits

    lines = [
        "",
        "// Area ablation s0: keep runtime two's-complement to sign-magnitude",
        "// conversion on the weight side instead of assuming offline conversion.",
        "wire " + ", ".join(f"{name}_sign" for name in names) + ";",
        f"wire [{mag_bits - 1}:0] " + ", ".join(f"{name}_mag" for name in names) + ";",
        f"wire [{w_bits - 1}:0] " + ", ".join(f"{name}_temp_mag" for name in names) + ";",
        "",
    ]
    for name in names:
        lines.extend(
            [
                f"assign {name}_sign = {name}[{w_bits - 1}];",
                (
                    f"assign {name}_temp_mag = {name}[{w_bits - 1}] ? "
                    f"(~{name}[{w_bits - 1}:0] + 1'b1) : {name}[{w_bits - 1}:0];"
                ),
                (
                    f"assign {name}_mag = ({name}_temp_mag == "
                    f"{verilog_literal(w_bits, min_negative)}) ? "
                    f"{verilog_literal(mag_bits, saturated_mag)} : "
                    f"{name}_temp_mag[{mag_bits - 1}:0];"
                ),
                "",
            ]
        )
    block = "\n".join(lines)

    updated, count = re.subn(
        r"\n\s*wire\s+w1_sign[\s\S]*?(?=\n\s*wire\s+a1_sign)",
        "\n" + block,
        text,
        count=1,
    )
    if count != 1:
        raise ValueError(f"Could not replace weight conversion block for {precision}")
    return updated


def make_dsp_c_combinational(text: str) -> str:
    match = re.search(
        r"(wire\s+\[47:0\]\s+dsp_C\s*=\s*)(.*?)(;\s*\n\s*always\s*@\(posedge clk\))",
        text,
        flags=re.DOTALL,
    )
    if not match:
        raise ValueError("Could not locate dsp_C expression")

    expr = match.group(2)
    expr = re.sub(r"\bmode_r1\b", "mode", expr)
    expr = re.sub(r"\b(LSB_[A-Za-z0-9_]+)_r1\b", r"\1", expr)

    return text[: match.start(2)] + expr + text[match.end(2) :]


def make_twos_complement_outputs(text: str) -> str:
    def replace(match: re.Match[str]) -> str:
        expr = match.group("expr").strip()
        width = int(match.group("width"))
        sign = match.group("sign")
        one = verilog_literal(width, ("0" * (width - 1)) + "1")
        return f"({sign} ? (~{expr} + {one}) : {expr})"

    updated = XOR_RESULT_RE.sub(replace, text)
    if updated == text:
        raise ValueError("No XOR sign-recovery assignments were replaced")
    return updated


def add_header(text: str, precision: str, top: str, stage: str, note: str, source: Path) -> str:
    rel_source = source.relative_to(REBUTTAL_ROOT).as_posix()
    return (
        "/*\n"
        " * Auto-generated for the Ultra-DSP rebuttal area ablation.\n"
        f" * Top module: {top}\n"
        f" * Precision: {precision}\n"
        f" * Stage: {stage}\n"
        f" * Source: {rel_source}\n"
        f" * Toggle summary: {note}\n"
        " */\n\n"
        + text.lstrip()
    )


def emit_optimization_stage(precision: str, stage: str, note: str) -> tuple[str, Path, Path]:
    top = f"{precision}_stage_{stage}"

    if precision == "W4A4":
        source = W4A4_STAGE_SOURCES[stage]
        text = read_text(source)
    else:
        source = PRECISIONS[precision]["source"]
        text = read_text(source)
        if stage == "s0_original":
            text = make_twos_complement_outputs(text)
            text = make_dsp_c_combinational(text)
            text = make_runtime_weight_conversion(text, precision)
        elif stage == "s1_weight_offline":
            text = make_twos_complement_outputs(text)
            text = make_dsp_c_combinational(text)
        elif stage == "s2_registered_c":
            text = make_twos_complement_outputs(text)
        elif stage == "s3_xor_sign":
            pass
        else:
            raise ValueError(f"Unknown stage {stage}")

    text = rename_top(text, top)
    text = add_header(text, precision, top, stage, note, source)
    out_path = OPT_DIR / f"{top}.v"
    write_text(out_path, text)
    return top, out_path, source


def emit_lsb_module(precision: str, depth: int) -> tuple[str, Path]:
    cfg = PRECISIONS[precision]
    w_mag_bits = cfg["w_bits"] - 1
    a_mag_bits = cfg["a_bits"] - 1
    top = f"{precision}_lsb_depth{depth}"

    partial_rows = []
    for w_idx in range(w_mag_bits):
        bits = []
        for out_idx in range(depth):
            a_idx = out_idx - w_idx
            if 0 <= a_idx < a_mag_bits:
                bits.append(f"a_mag[{a_idx}]")
            else:
                bits.append("1'b0")
        if all(bit == "1'b0" for bit in bits):
            continue
        literal = "{" + ", ".join(reversed(bits)) + "}"
        partial_rows.append((w_idx, literal))

    partial_decl = []
    for row_idx, (w_idx, literal) in enumerate(partial_rows):
        partial_decl.append(
            f"wire [{depth - 1}:0] partial_{row_idx} = w_mag[{w_idx}] ? {literal} : {depth}'b0;"
        )

    if len(partial_rows) == 1:
        sum_logic = "assign lsb = partial_0;"
    else:
        sum_lines = [f"wire [{depth - 1}:0] sum_0 = partial_0;"]
        for row_idx in range(1, len(partial_rows)):
            sum_lines.append(
                f"wire [{depth - 1}:0] sum_{row_idx} = sum_{row_idx - 1} + partial_{row_idx};"
            )
        sum_lines.append(f"assign lsb = sum_{len(partial_rows) - 1};")
        sum_logic = "\n".join(sum_lines)

    text = f"""/*
 * Auto-generated for the Ultra-DSP rebuttal LSB-depth sweep.
 * Top module: {top}
 * Precision: {precision}
 * Magnitude widths: W={w_mag_bits}, A={a_mag_bits}
 * Depth: {depth}
 *
 * This isolates one low-product-bit correction generator. It builds only the
 * low DEPTH bits with a truncated partial-product network, so Vivado can expose
 * the incremental LUT cost of increasing LSB depth.
 */

(* keep_hierarchy = \"yes\", use_dsp = \"no\" *)
module {top}(
    input wire [{w_mag_bits - 1}:0] w_mag,
    input wire [{a_mag_bits - 1}:0] a_mag,
    output wire [{depth - 1}:0] lsb
);

{chr(10).join(partial_decl)}

{sum_logic}

endmodule
"""
    out_path = LSB_DIR / f"{top}.v"
    write_text(out_path, text)
    return top, out_path


def main() -> None:
    rows = []
    for precision in PRECISIONS:
        for stage, note in STAGES:
            top, out_path, source = emit_optimization_stage(precision, stage, note)
            rows.append(
                {
                    "top_module": top,
                    "precision": precision,
                    "experiment": "optimization_stage",
                    "variant": stage,
                    "rtl_file": out_path.relative_to(ROOT).as_posix(),
                    "source_file": source.relative_to(REBUTTAL_ROOT).as_posix(),
                    "notes": note,
                }
            )

    for precision in PRECISIONS:
        for depth in range(1, 7):
            top, out_path = emit_lsb_module(precision, depth)
            rows.append(
                {
                    "top_module": top,
                    "precision": precision,
                    "experiment": "lsb_depth",
                    "variant": f"depth{depth}",
                    "rtl_file": out_path.relative_to(ROOT).as_posix(),
                    "source_file": "",
                    "notes": "single correction low-product generator with use_dsp=no",
                }
            )

    with MANIFEST.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "top_module",
                "precision",
                "experiment",
                "variant",
                "rtl_file",
                "source_file",
                "notes",
            ],
        )
        writer.writeheader()
        writer.writerows(rows)

    print(f"Wrote {len(rows)} ablation entries under {ROOT}")


if __name__ == "__main__":
    main()
