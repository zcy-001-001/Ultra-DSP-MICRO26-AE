@dataclass(frozen=True)
class ProductTerm:
    out_idx: int
    w_idx: int
    a_idx: int
    start: int
    overlap: int


def parse_positions(value: str) -> list[int]:
    if isinstance(value, str):
        return [int(item) for item in value.split() if item]
    return list(value)


def module_safe(name: str) -> str:
    return "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in name)


def header(fmt: FPFormat, top: str, design: str, width: int, products_per_dsp: int) -> str:
    return f"""`timescale 1ns/1ps

/*
 * Auto-generated by scripts/generate_fp_pe_rtl.py.
 * Top module: {top}
 * Format: {fmt.name} ({fmt.label})
 * Product kind: {fmt.product_kind}
 * Design: {design}
 * Decoded operand width: {width} bits
 * Products per DSP: {products_per_dsp}
 *
 * Scope: this PE validates the decoded unsigned mantissa/magnitude product
 * backend. FP exponent, shared scale, rounding, saturation, and repacking stay
 * outside this single-DSP datapath.
 */

"""


def port_decl(prefix: str, count: int, width: int, direction: str = "input wire") -> str:
    return "\n".join(f"    {direction} [{width - 1}:0] {prefix}{idx}," for idx in range(count))


def packed_product_terms(x_pos: list[int], y_pos: list[int], product_width: int) -> list[ProductTerm]:
    raw = []
    for wi, xp in enumerate(x_pos):
        for ai, yp in enumerate(y_pos):
            raw.append((xp + yp, wi, ai))
    raw.sort()
    terms = []
    prev_start = None
    for out_idx, (start, wi, ai) in enumerate(raw):
        overlap = 0 if prev_start is None else max(0, prev_start + product_width - start)
        terms.append(ProductTerm(out_idx=out_idx, w_idx=wi, a_idx=ai, start=start, overlap=overlap))
        prev_start = start
    return terms


def _lut6_init_for_low_product_bit(width: int, bit_idx: int) -> tuple[int, list[str]]:
    inputs: list[tuple[str, int]] = []
    for idx in range(min(width, bit_idx + 1)):
        inputs.append(("lhs", idx))
    for idx in range(min(width, bit_idx + 1)):
        inputs.append(("rhs", idx))
    if len(inputs) > 6:
        raise ValueError(
            f"low product bit {bit_idx} for width {width} needs {len(inputs)} inputs; "
            "one LUT6 is not enough"
        )

    init = 0
    for lut_addr in range(64):
        lhs = 0
        rhs = 0
        for lut_pin, (kind, bit) in enumerate(inputs):
            value = (lut_addr >> lut_pin) & 1
            if kind == "lhs":
                lhs |= value << bit
            else:
                rhs |= value << bit
        if ((lhs * rhs) >> bit_idx) & 1:
            init |= 1 << lut_addr
    ports = [f"{kind}[{bit}]" for kind, bit in inputs]
    while len(ports) < 6:
        ports.append("1'b0")
    return init, ports


def _ports_for_low_product_bits(width: int, bit_indices: tuple[int, ...]) -> list[tuple[str, int]]:
    ports: list[tuple[str, int]] = []
    for bit_idx in bit_indices:
        for idx in range(min(width, bit_idx + 1)):
            item = ("lhs", idx)
            if item not in ports:
                ports.append(item)
        for idx in range(min(width, bit_idx + 1)):
            item = ("rhs", idx)
            if item not in ports:
                ports.append(item)
    return ports


def _eval_low_product_bit(width: int, bit_idx: int, addr: int, ports: list[tuple[str, int] | None]) -> int:
    lhs = 0
    rhs = 0
    for lut_pin, item in enumerate(ports):
        if item is None:
            continue
        kind, bit = item
        value = (addr >> lut_pin) & 1
        if kind == "lhs":
            lhs |= value << bit
        else:
            rhs |= value << bit
    return (lhs * rhs >> bit_idx) & 1


def _lut6_2_init_for_low_product_bits(width: int, o5_bit: int, o6_bit: int) -> tuple[int, list[str]]:
    port_items: list[tuple[str, int] | None] = _ports_for_low_product_bits(width, (o5_bit, o6_bit))
    if len(port_items) > 5:
        raise ValueError(
            f"low product bits {o5_bit}/{o6_bit} for width {width} need {len(port_items)} shared inputs; "
            "LUT6_2 O5 can only use I0..I4"
        )
    while len(port_items) < 5:
        port_items.append(None)

    init = 0
    for addr in range(64):
        if (addr >> 5) & 1:
            value = _eval_low_product_bit(width, o6_bit, addr, port_items)
        else:
            value = _eval_low_product_bit(width, o5_bit, addr, port_items)
        if value:
            init |= 1 << addr

    ports = [f"{kind}[{bit}]" if item is not None else "1'b0" for item in port_items for kind, bit in ([item] if item is not None else [])]
    while len(ports) < 5:
        ports.append("1'b0")
    ports.append("1'b1")
    return init, ports


def _lut6_2_init_for_two_and_pairs() -> int:
    init = 0
    for addr in range(64):
        i0 = (addr >> 0) & 1
        i1 = (addr >> 1) & 1
        i2 = (addr >> 2) & 1
        i3 = (addr >> 3) & 1
        if (addr >> 5) & 1:
            value = i2 & i3
        else:
            value = i0 & i1
        if value:
            init |= 1 << addr
    return init


def low_product_lut6_pair_module(width: int) -> str:
    if width != 1:
        return ""
    init = _lut6_2_init_for_two_and_pairs()
    return f"""
// Synthesis-only LUT6_2 pair for two independent 1-bit correction products.
// One physical LUT computes both lhs0&rhs0 and lhs1&rhs1 through O5/O6.
module fp_lut6_2_low_product_pair_w1(
    input wire [0:0] lhs0,
    input wire [0:0] rhs0,
    input wire [0:0] lhs1,
    input wire [0:0] rhs1,
    output wire [0:0] out0,
    output wire [0:0] out1
);

`ifdef SYNTHESIS
(* DONT_TOUCH = "yes", KEEP = "yes" *)
LUT6_2 #(.INIT(64'h{init:016X})) pair_lut (
    .I0(lhs0[0]),
    .I1(rhs0[0]),
    .I2(lhs1[0]),
    .I3(rhs1[0]),
    .I4(1'b0),
    .I5(1'b1),
    .O5(out0[0]),
    .O6(out1[0])
);
`else
assign out0 = lhs0 * rhs0;
assign out1 = lhs1 * rhs1;
`endif

endmodule
"""


def low_product_lut6_module(width: int, low_bits: int) -> str:
    if low_bits <= 0:
        return ""
    module_name = f"fp_lut6_low_product_w{width}_l{low_bits}"
    text = f"""
// Synthesis-only LUT6 implementation for correction low bits.  This
// supersedes the previous behavioral low_product_bits function because Vivado
// could otherwise absorb 1-bit products into FF control/reset pins and make
// the reported LUT area look artificially small.
module {module_name}(
    input wire [{width - 1}:0] lhs,
    input wire [{width - 1}:0] rhs,
    output wire [{low_bits - 1}:0] out
);

`ifdef SYNTHESIS
"""
    bit_idx = 0
    if low_bits >= 2:
        init, ports = _lut6_2_init_for_low_product_bits(width, 0, 1)
        text += f"""(* DONT_TOUCH = "yes", KEEP = "yes" *)
LUT6_2 #(.INIT(64'h{init:016X})) low_lut_0_1 (
    .I0({ports[0]}),
    .I1({ports[1]}),
    .I2({ports[2]}),
    .I3({ports[3]}),
    .I4({ports[4]}),
    .I5({ports[5]}),
    .O5(out[0]),
    .O6(out[1])
);
"""
        bit_idx = 2

    while bit_idx < low_bits:
        init, ports = _lut6_init_for_low_product_bit(width, bit_idx)
        text += f"""(* DONT_TOUCH = "yes", KEEP = "yes" *)
LUT6 #(.INIT(64'h{init:016X})) low_lut_{bit_idx} (
    .I0({ports[0]}),
    .I1({ports[1]}),
    .I2({ports[2]}),
    .I3({ports[3]}),
    .I4({ports[4]}),
    .I5({ports[5]}),
    .O(out[{bit_idx}])
);
"""
        bit_idx += 1
    text += f"""`else
wire [{2 * width - 1}:0] product = lhs * rhs;
assign out = product[{low_bits - 1}:0];
`endif

endmodule
"""
    return text


def emit_scalar(fmt: FPFormat, out_dir: Path) -> dict[str, str | int]:
    width = fmt.product_width
    prod_width = 2 * width
    top = module_safe(f"{fmt.name}_NoPackingScalar")
    text = header(fmt, top, "NoPackingScalar", width, 1)
    text += DSP_HELPER
    text += f"""
module {top}(
    input wire clk,
    input wire [{width - 1}:0] w0,
    input wire [{width - 1}:0] a0,
"""
    text += f"""
    output wire [{prod_width - 1}:0] mag0,
"""
    text += f"""
    output wire [7:0] valid_count
);

wire [26:0] dsp_a = {{{27 - width}'b0, w0}};
wire [17:0] dsp_b = {{{18 - width}'b0, a0}};
wire [47:0] dsp_p;

fp_dsp48e2_m_sub_c dsp_core (
    .clk(clk),
    .dsp_a(dsp_a),
    .dsp_b(dsp_b),
    .dsp_c(48'b0),
    .dsp_p(dsp_p)
);

assign mag0 = dsp_p[{prod_width - 1}:0];
"""
    text += """
assign valid_count = 8'd1;

endmodule
"""
    out_path = out_dir / f"{top}.v"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text, encoding="utf-8", newline="\n")
    return {
        "format": fmt.name,
        "format_label": fmt.label,
        "product_kind": fmt.product_kind,
        "design": "NoPackingScalar",
        "top_module": top,
        "rtl_file": str(out_path.relative_to(ROOT)).replace("\\", "/"),
        "product_width": width,
        "nx": 1,
        "ny": 1,
        "products_per_dsp": 1,
        "x_pos": "0",
        "y_pos": "0",
        "result_starts": "0",
        "max_result_overlap": 0,
    }


def emit_packed(fmt: FPFormat, design: str, max_overlap: int, out_dir: Path) -> dict[str, str | int]:
    width = fmt.product_width
    prod_width = 2 * width
    layout = choose_best_layout(width, max_overlap)
    # The original notebook uses X_lim=17 for the DSP B port and Y_lim=26 for
    # the DSP A port.  The generated PE names weights as A-port operands and
    # activations as B-port operands, so swap the solver positions here.
    solver_b_pos = parse_positions(layout["x_pos"])
    solver_a_pos = parse_positions(layout["y_pos"])
    w_pos = solver_a_pos
    a_pos = solver_b_pos
    terms = packed_product_terms(w_pos, a_pos, prod_width)
    products_per_dsp = len(terms)
    top = module_safe(f"{fmt.name}_{design.replace('-', '_')}")
    max_actual_overlap = max((term.overlap for term in terms), default=0)
    # Supersedes the earlier conservative `max(max_overlap, max_actual_overlap)`.
    # The correction datapath only needs the actual overlapped low bits; tying
    # this width to the solver constraint over-counts FFs for small-width rows.
    low_bits = max_actual_overlap

    text = header(fmt, top, design, width, products_per_dsp)
    text += DSP_HELPER
    if low_bits == 1:
        text += low_product_lut6_pair_module(width)
    text += low_product_lut6_module(width, low_bits)
    text += f"""
module {top}(
    input wire clk,
{port_decl("w", len(w_pos), width)}
{port_decl("a", len(a_pos), width)}
"""
    for term in terms:
        text += f"    output wire [{prod_width - 1}:0] mag{term.out_idx},\n"
    text += "    output wire [7:0] valid_count\n);\n"

    a_terms = [f"({{{27 - width}'b0, w{idx}}} << {pos})" for idx, pos in enumerate(w_pos)]
    b_terms = [f"({{{18 - width}'b0, a{idx}}} << {pos})" for idx, pos in enumerate(a_pos)]
    text += "\nwire [26:0] dsp_a = " + " |\n    ".join(a_terms) + ";\n"
    text += "wire [17:0] dsp_b = " + " |\n    ".join(b_terms) + ";\n"

    if low_bits > 0 and any(term.overlap > 0 for term in terms):
        overlapped_terms = [term for term in terms if term.overlap > 0]
        for term in overlapped_terms:
            if term.overlap <= 0:
                continue
            text += f"wire [{low_bits - 1}:0] low{term.out_idx};\n"

        if low_bits == 1 and width == 1:
            for pair_idx in range(0, len(overlapped_terms), 2):
                first = overlapped_terms[pair_idx]
                second = overlapped_terms[pair_idx + 1] if pair_idx + 1 < len(overlapped_terms) else None
                if second is not None:
                    text += (
                        f"fp_lut6_2_low_product_pair_w1 low{first.out_idx}_low{second.out_idx}_lut6_2_inst (\n"
                        f"    .lhs0(w{first.w_idx}),\n"
                        f"    .rhs0(a{first.a_idx}),\n"
                        f"    .lhs1(w{second.w_idx}),\n"
                        f"    .rhs1(a{second.a_idx}),\n"
                        f"    .out0(low{first.out_idx}),\n"
                        f"    .out1(low{second.out_idx})\n"
                        f");\n"
                    )
                else:
                    text += (
                        f"fp_lut6_low_product_w{width}_l{low_bits} low{first.out_idx}_lut6_inst (\n"
                        f"    .lhs(w{first.w_idx}),\n"
                        f"    .rhs(a{first.a_idx}),\n"
                        f"    .out(low{first.out_idx})\n"
                        f");\n"
                    )
        else:
            for term in overlapped_terms:
                text += (
                    f"fp_lut6_low_product_w{width}_l{low_bits} low{term.out_idx}_lut6_inst (\n"
                    f"    .lhs(w{term.w_idx}),\n"
                    f"    .rhs(a{term.a_idx}),\n"
                    f"    .out(low{term.out_idx})\n"
                    f");\n"
                )

        text += "\n"
        for suffix in ("r1", "r2", "r3"):
            decls = [
                f"low{term.out_idx}_{suffix}"
                for term in terms
                if term.overlap > 0
            ]
            text += f"reg [{low_bits - 1}:0] " + ", ".join(decls) + ";\n"

        text += "\nalways @(posedge clk) begin\n"
        for term in terms:
            if term.overlap > 0:
                text += f"    low{term.out_idx}_r1 <= low{term.out_idx};\n"
        text += "end\n\nalways @(posedge clk) begin\n"
        for term in terms:
            if term.overlap > 0:
                text += f"    low{term.out_idx}_r2 <= low{term.out_idx}_r1;\n"
        text += "end\n\nalways @(posedge clk) begin\n"
        for term in terms:
            if term.overlap > 0:
                text += f"    low{term.out_idx}_r3 <= low{term.out_idx}_r2;\n"
        text += "end\n"

        corr_terms = []
        for term in terms:
            if term.overlap <= 0:
                continue
            corr_terms.append(
                f"({{{48 - term.overlap}'b0, low{term.out_idx}_r1[{term.overlap - 1}:0]}} << {term.start})"
            )
        text += "\nwire [47:0] dsp_c = " + " |\n    ".join(corr_terms) + ";\n"
    else:
        text += "\nwire [47:0] dsp_c = 48'b0;\n"

    text += """
wire [47:0] dsp_p;

fp_dsp48e2_m_sub_c dsp_core (
    .clk(clk),
    .dsp_a(dsp_a),
    .dsp_b(dsp_b),
    .dsp_c(dsp_c),
    .dsp_p(dsp_p)
);

"""
    for term in terms:
        if term.overlap > 0:
            high_msb = term.start + prod_width - 1
            high_lsb = term.start + term.overlap
            low_slice = f"low{term.out_idx}_r3[{term.overlap - 1}:0]"
            text += f"assign mag{term.out_idx} = {{dsp_p[{high_msb}:{high_lsb}], {low_slice}}};\n"
        else:
            text += f"assign mag{term.out_idx} = dsp_p[{term.start + prod_width - 1}:{term.start}];\n"
    text += f"assign valid_count = 8'd{products_per_dsp};\n\nendmodule\n"

    out_path = out_dir / f"{top}.v"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text, encoding="utf-8", newline="\n")
    return {
        "format": fmt.name,
        "format_label": fmt.label,
        "product_kind": fmt.product_kind,
        "design": design,
        "top_module": top,
        "rtl_file": str(out_path.relative_to(ROOT)).replace("\\", "/"),
        "product_width": width,
        "nx": len(w_pos),
        "ny": len(a_pos),
        "products_per_dsp": products_per_dsp,
        "x_pos": " ".join(map(str, w_pos)),
        "y_pos": " ".join(map(str, a_pos)),
        "result_starts": " ".join(str(term.start) for term in terms),
        "max_result_overlap": max_actual_overlap,
    }


def emit_lut_parallel(fmt: FPFormat, out_dir: Path) -> dict[str, str | int]:
    """Emit a pure-LUT same-throughput baseline matched to UltraDSP T.

    This baseline is intentionally different from NoPackingScalar.  It uses no
    DSP and instantiates T independent LUT multipliers, where T is the
    UltraDSP-Packing products/cycle for the same input width.
    """

    width = fmt.product_width
    prod_width = 2 * width
    layout = choose_best_layout(width, 3)
    solver_b_pos = parse_positions(layout["x_pos"])
    solver_a_pos = parse_positions(layout["y_pos"])
    w_pos = solver_a_pos
    a_pos = solver_b_pos
    terms = packed_product_terms(w_pos, a_pos, prod_width)
    products = len(terms)
    top = module_safe(f"{fmt.name}_NoDSP_LUTParallel")

    text = header(fmt, top, "NoDSP_LUTParallel", width, products)
    text += f"""
(* use_dsp = "no" *)
module {top}(
    input wire clk,
{port_decl("w", len(w_pos), width)}
{port_decl("a", len(a_pos), width)}
"""
    for term in terms:
        text += f"    output wire [{prod_width - 1}:0] mag{term.out_idx},\n"
    text += "    output wire [7:0] valid_count\n);\n\n"

    text += "// Pure-LUT same-throughput baseline: no packed DSP, no correction network.\n"
    text += "// Each output product is an independent decoded mantissa/magnitude multiply.\n"
    for term in terms:
        text += (
            f"(* use_dsp = \"no\" *) wire [{prod_width - 1}:0] prod{term.out_idx} = "
            f"w{term.w_idx} * a{term.a_idx};\n"
        )
    text += "\n"
    for term in terms:
        text += f"assign mag{term.out_idx} = prod{term.out_idx};\n"
    text += f"assign valid_count = 8'd{products};\n\nendmodule\n"

    out_path = out_dir / f"{top}.v"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text, encoding="utf-8", newline="\n")
    return {
        "format": fmt.name,
        "format_label": fmt.label,
        "product_kind": fmt.product_kind,
        "design": "NoDSP_LUTParallel",
        "top_module": top,
        "rtl_file": str(out_path.relative_to(ROOT)).replace("\\", "/"),
        "product_width": width,
        "nx": len(w_pos),
        "ny": len(a_pos),
        "products_per_dsp": products,
        "x_pos": " ".join(map(str, w_pos)),
        "y_pos": " ".join(map(str, a_pos)),
        "result_starts": " ".join(str(term.start) for term in terms),
        "max_result_overlap": 0,
    }


def write_manifest(rows: list[dict[str, str | int]], out: Path) -> None:
    fieldnames = [
        "format",
        "format_label",
        "product_kind",
        "design",
        "top_module",
        "rtl_file",
        "product_width",
        "nx",
        "ny",
        "products_per_dsp",
        "x_pos",
        "y_pos",
        "result_starts",
        "max_result_overlap",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {len(rows)} RTL entries to {out}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rtl-dir", default="rtl")
    parser.add_argument("--manifest", default="manifest.csv")
    parser.add_argument("--formats", nargs="*", default=None)
    args = parser.parse_args()

    rtl_dir = Path(args.rtl_dir)
    if not rtl_dir.is_absolute():
        rtl_dir = ROOT / rtl_dir
    manifest = Path(args.manifest)
    if not manifest.is_absolute():
        manifest = ROOT / manifest

    rows: list[dict[str, str | int]] = []
    for fmt in iter_formats(args.formats):
        rows.append(emit_scalar(fmt, rtl_dir))
        rows.append(emit_packed(fmt, "NormalNonOverlap", 0, rtl_dir))
        rows.append(emit_packed(fmt, "UltraDSP-Packing", 3, rtl_dir))
        rows.append(emit_lut_parallel(fmt, rtl_dir))
    write_manifest(rows, manifest)


if __name__ == "__main__":
    main()
