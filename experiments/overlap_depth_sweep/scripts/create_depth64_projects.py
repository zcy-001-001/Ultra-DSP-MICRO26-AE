def json_port(name: str, direction: str, data_key: str) -> dict[str, object]:
    ports: dict[str, str] = {}
    if direction == "in":
        ports = {
            "RAM_address": f"{name}_address",
            "RAM_clock_enable": f"{name}_ce",
            "RAM_data_read_in": name,
        }
    else:
        ports = {
            "RAM_address": f"{name}_address",
            "RAM_clock_enable": f"{name}_ce",
            "RAM_write_enable": f"{name}_we",
            "RAM_data_write_out": name,
        }
    return {
        "c_name": name,
        "c_port_direction": direction,
        "RAM_type": "RAM_1P",
        "rtl_ports": ports,
    }


def generate_json(layout: Layout, remote_project: str) -> str:
    c_params: list[dict[str, object]] = [
        {
            "c_name": "mode",
            "c_port_direction": "in",
            "rtl_ports": {"data_read_in": "mode"},
        }
    ]
    c_params += [json_port(f"w{idx}", "in", "RAM_data_read_in") for idx in range(1, DECODING_WEIGHTS + 1)]
    c_params += [json_port(f"a{idx}", "in", "RAM_data_read_in") for idx in range(1, layout.act_groups + 1)]
    c_params += [json_port(f"result{idx}", "out", "RAM_data_write_out") for idx in range(1, layout.result_ports + 1)]
    data = {
        "c_function_name": layout.top,
        "rtl_top_module_name": layout.top,
        "c_files": [{"c_file": f"{remote_project}/src/{layout.top}.cpp", "cflag": ""}],
        "rtl_files": [f"{remote_project}/src/{layout.top}_wrapper.v"],
        "c_parameters": c_params,
        "rtl_common_signal": {
            "module_clock": "ap_clk",
            "module_reset": "ap_rst",
            "module_clock_enable": "ap_ce",
            "ap_ctrl_chain_protocol_idle": "ap_idle",
            "ap_ctrl_chain_protocol_start": "ap_start",
            "ap_ctrl_chain_protocol_ready": "ap_ready",
            "ap_ctrl_chain_protocol_done": "ap_done",
            "ap_ctrl_chain_protocol_continue": "ap_continue",
        },
        "rtl_performance": {"latency": "3", "II": "1"},
        "rtl_resource_usage": {
            "FF": str(layout.ff_per_pe * NUM_PE),
            "LUT": str(layout.lut_per_pe * NUM_PE),
            "BRAM": "0",
            "URAM": "0",
            "DSP": str(NUM_PE),
        },
    }
    return json.dumps(data, indent=2) + "\n"


