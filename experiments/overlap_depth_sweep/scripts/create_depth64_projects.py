def copy_scripts(dst: Path) -> None:
    for script in ["csynth.sh", "ooc_implement.sh", "env.sh"]:
        shutil.copy2(PD64_TEMPLATE / script, dst / script)
    shutil.copy2(PD64_TEMPLATE / "src" / "u55C.cfg", dst / "src" / "u55C.cfg")


def emit_project(layout: Layout) -> None:
    project_dir = OUT_ROOT / layout.project
    if project_dir.exists():
        shutil.rmtree(project_dir)
    (project_dir / "src").mkdir(parents=True)
    (project_dir / "config" / "generated").mkdir(parents=True)
    copy_scripts(project_dir)

    remote_project = f"{REMOTE_BASE}/{layout.project}"
    files = {
        project_dir / "src" / "GEMV.h": generate_h(layout),
        project_dir / "src" / "GEMV.cpp": generate_gemv_cpp(layout),
        project_dir / "src" / f"{layout.top}.cpp": generate_blackbox_cpp(layout),
        project_dir / "src" / f"{layout.top}.json": generate_json(layout, remote_project),
        project_dir / "src" / f"{layout.top}_wrapper.v": generate_wrapper(layout),
        project_dir / "config" / "hls_template.cfg": generate_hls_template(layout),
        project_dir / "config" / "hls.cfg": generate_hls_cfg(layout),
        project_dir / "config" / "frequency_sweep.cfg": generate_frequency_sweep(),
        project_dir / "README.md": generate_readme(layout),
    }
    for path, text in files.items():
        path.write_text(text, encoding="utf-8", newline="\n")


def main() -> None:
    if not PD64_TEMPLATE.exists():
        raise FileNotFoundError(f"Missing template copy: {PD64_TEMPLATE}")
    if not RTL_DIR.exists():
        raise FileNotFoundError(f"Missing generated RTL dir: {RTL_DIR}")
    OUT_ROOT.mkdir(parents=True, exist_ok=True)
    for layout in LAYOUTS:
        emit_project(layout)
        print(f"wrote {OUT_ROOT / layout.project}")


if __name__ == "__main__":
    main()
