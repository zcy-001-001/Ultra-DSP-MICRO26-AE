def product_map(layout: Layout) -> list[tuple[int, int, int, int]]:
    """Return (result_index, start, weight_index, activation_index)."""
    products: list[tuple[int, int, int]] = []
    for act_idx, x in enumerate(layout.prefill_x, start=1):
        for weight_idx, y in enumerate(layout.prefill_y, start=1):
            products.append((x + y, weight_idx, act_idx))
    products.sort()
    return [
        (result_idx, start, weight_idx, act_idx)
        for result_idx, (start, weight_idx, act_idx) in enumerate(products, start=1)
    ]


def indent(lines: list[str], spaces: int) -> str:
    pad = " " * spaces
    return "\n".join(pad + line if line else "" for line in lines)


def port_list(prefix: str, count: int) -> str:
    return ", ".join(f"{prefix}{idx}" for idx in range(1, count + 1))


