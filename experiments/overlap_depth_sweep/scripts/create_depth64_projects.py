@dataclass(frozen=True)
class Layout:
    depth: int
    project: str
    top: str
    prefill_x: tuple[int, ...]
    prefill_y: tuple[int, ...]
    lut_per_pe: int
    ff_per_pe: int

    @property
    def act_groups(self) -> int:
        return len(self.prefill_x)

    @property
    def prefill_weights(self) -> int:
        return len(self.prefill_y)

    @property
    def prefill_results(self) -> int:
        return self.act_groups * self.prefill_weights

    @property
    def result_ports(self) -> int:
        return max(self.prefill_results, DECODING_WEIGHTS)


